-- Catalogó comun de formularios y preguntas versionados
-- PostgreSQL 17 / Flyway
-- No contiene preguntas psicometricas ni datos personales.

-- =====================================================
-- 1. TEST
-- =====================================================

CREATE TABLE test (
                    id_test BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    codigo VARCHAR(80) NOT NULL UNIQUE,
                    nombre VARCHAR(200) NOT NULL,
                    descripcion TEXT,
                    activo BOOLEAN NOT NULL DEFAULT TRUE,

                    CONSTRAINT chk_test_codigo
                      CHECK (BTRIM(codigo) <> ''),

                    CONSTRAINT chk_test_nombre
                      CHECK (BTRIM(nombre) <> ''),

                    CONSTRAINT chk_test_descripcion
                      CHECK (descripcion IS NULL OR BTRIM(descripcion) <> '')
);

-- =====================================================
-- 2. SUBPRUEBA
-- =====================================================

CREATE TABLE subprueba (
                         id_subprueba BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         id_test BIGINT NOT NULL,
                         codigo VARCHAR(80) NOT NULL,
                         nombre VARCHAR(200) NOT NULL,
                         descripcion TEXT,

                         CONSTRAINT fk_subprueba_test
                           FOREIGN KEY (id_test) REFERENCES test(id_test),

                         CONSTRAINT uq_subprueba_test_codigo
                           UNIQUE (id_test, codigo),

                         CONSTRAINT chk_subprueba_codigo
                           CHECK (BTRIM(codigo) <> ''),

                         CONSTRAINT chk_subprueba_nombre
                           CHECK (BTRIM(nombre) <> ''),

                         CONSTRAINT chk_subprueba_descripcion
                           CHECK (descripcion IS NULL OR BTRIM(descripcion) <> '')
);

-- =====================================================
-- 3. VERSION FORMULARIO
-- =====================================================

CREATE TABLE version_formulario (
                                  id_version_formulario BIGINT
                                    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                  id_test BIGINT NOT NULL,
                                  codigo_version VARCHAR(80) NOT NULL,
                                  descripcion TEXT,
                                  estado VARCHAR(20) NOT NULL DEFAULT 'BORRADOR',
                                  fuente_ref TEXT NOT NULL,
                                  publicada_en TIMESTAMPTZ,
                                  evidencia_validacion TEXT,

                                  CONSTRAINT fk_version_test
                                    FOREIGN KEY (id_test) REFERENCES test(id_test),

                                  CONSTRAINT uq_version_test_codigo
                                    UNIQUE (id_test, codigo_version),

                                  CONSTRAINT chk_version_codigo
                                    CHECK (BTRIM(codigo_version) <> ''),

                                  CONSTRAINT chk_version_descripcion
                                    CHECK (descripcion IS NULL OR BTRIM(descripcion) <> ''),

                                  CONSTRAINT chk_version_estado
                                    CHECK (estado IN ('BORRADOR', 'PUBLICADA', 'RETIRADA')),

                                  CONSTRAINT chk_version_fuente
                                    CHECK (BTRIM(fuente_ref) <> ''),

                                  CONSTRAINT chk_version_evidencia
                                    CHECK (
                                      evidencia_validacion IS NULL
                                        OR BTRIM(evidencia_validacion) <> ''
                                      ),

                                  CONSTRAINT chk_version_publicacion
                                    CHECK (
                                      estado = 'BORRADOR'
                                        OR (
                                        publicada_en IS NOT NULL
                                          AND evidencia_validacion IS NOT NULL
                                        )
                                      )
);

-- =====================================================
-- 4. CONFIGURACION SUBPRUEBA
-- =====================================================

CREATE TABLE configuracion_subprueba (
                                       id_configuracion_subprueba BIGINT
                                         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                       id_version_formulario BIGINT NOT NULL,
                                       id_subprueba BIGINT NOT NULL,
                                       orden_aplicacion INTEGER NOT NULL,
                                       tiempo_limite_segundos INTEGER,
                                       tipo_respuesta VARCHAR(20) NOT NULL,
                                       instrucciones_ref TEXT NOT NULL,
                                       practica_ref TEXT,
                                       maximo_entradas INTEGER,

                                       CONSTRAINT fk_config_version
                                         FOREIGN KEY (id_version_formulario)
                                           REFERENCES version_formulario(id_version_formulario),

                                       CONSTRAINT fk_config_subprueba
                                         FOREIGN KEY (id_subprueba)
                                           REFERENCES subprueba(id_subprueba),

                                       CONSTRAINT uq_config_version_subprueba
                                         UNIQUE (id_version_formulario, id_subprueba),

                                       CONSTRAINT uq_config_version_orden
                                         UNIQUE (id_version_formulario, orden_aplicacion),

                                       CONSTRAINT chk_config_orden
                                         CHECK (orden_aplicacion > 0),

                                       CONSTRAINT chk_config_tiempo
                                         CHECK (
                                           tiempo_limite_segundos IS NULL
                                             OR tiempo_limite_segundos > 0
                                           ),

                                       CONSTRAINT chk_config_tipo
                                         CHECK (tipo_respuesta IN ('SELECCION', 'TEXTO_LIBRE')),

                                       CONSTRAINT chk_config_instrucciones
                                         CHECK (BTRIM(instrucciones_ref) <> ''),

                                       CONSTRAINT chk_config_practica
                                         CHECK (
                                           practica_ref IS NULL
                                             OR BTRIM(practica_ref) <> ''
                                           ),

                                       CONSTRAINT chk_config_maximo
                                         CHECK (
                                           maximo_entradas IS NULL
                                             OR maximo_entradas > 0
                                           ),

                                       CONSTRAINT chk_config_entradas_seleccion
                                         CHECK (
                                           tipo_respuesta <> 'SELECCION'
                                             OR maximo_entradas IS NULL
                                           )
);

-- =====================================================
-- 5. PREGUNTA
-- =====================================================

CREATE TABLE pregunta (
                        id_pregunta BIGINT
                          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                        id_configuracion_subprueba BIGINT NOT NULL,
                        numero_visible VARCHAR(40) NOT NULL,
                        orden_presentacion INTEGER NOT NULL,
                        enunciado TEXT,
                        recurso_ref TEXT,

                        CONSTRAINT fk_pregunta_config
                          FOREIGN KEY (id_configuracion_subprueba)
                            REFERENCES configuracion_subprueba(id_configuracion_subprueba),

                        CONSTRAINT uq_pregunta_numero
                          UNIQUE (id_configuracion_subprueba, numero_visible),

                        CONSTRAINT uq_pregunta_orden
                          UNIQUE (id_configuracion_subprueba, orden_presentacion),

                        CONSTRAINT chk_pregunta_numero
                          CHECK (BTRIM(numero_visible) <> ''),

                        CONSTRAINT chk_pregunta_orden
                          CHECK (orden_presentacion > 0),

                        CONSTRAINT chk_pregunta_enunciado
                          CHECK (
                            enunciado IS NULL OR BTRIM(enunciado) <> ''
                            ),

                        CONSTRAINT chk_pregunta_recurso
                          CHECK (
                            recurso_ref IS NULL OR BTRIM(recurso_ref) <> ''
                            ),

                        CONSTRAINT chk_pregunta_contenido
                          CHECK (
                            enunciado IS NOT NULL OR recurso_ref IS NOT NULL
                            )
);

-- =====================================================
-- 6. OPCION RESPUESTA
-- =====================================================

CREATE TABLE opcion_respuesta (
                                id_opcion BIGINT
                                  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                id_pregunta BIGINT NOT NULL,
                                codigo VARCHAR(40) NOT NULL,
                                orden_presentacion INTEGER NOT NULL,
                                texto TEXT,
                                recurso_ref TEXT,

                                CONSTRAINT fk_opcion_pregunta
                                  FOREIGN KEY (id_pregunta)
                                    REFERENCES pregunta(id_pregunta),

                                CONSTRAINT uq_opcion_codigo
                                  UNIQUE (id_pregunta, codigo),

                                CONSTRAINT uq_opcion_orden
                                  UNIQUE (id_pregunta, orden_presentacion),

                                CONSTRAINT chk_opcion_codigo
                                  CHECK (BTRIM(codigo) <> ''),

                                CONSTRAINT chk_opcion_orden
                                  CHECK (orden_presentacion > 0),

                                CONSTRAINT chk_opcion_texto
                                  CHECK (
                                    texto IS NULL OR BTRIM(texto) <> ''
                                    ),

                                CONSTRAINT chk_opcion_recurso
                                  CHECK (
                                    recurso_ref IS NULL OR BTRIM(recurso_ref) <> ''
                                    ),

                                CONSTRAINT chk_opcion_contenido
                                  CHECK (
                                    texto IS NOT NULL OR recurso_ref IS NOT NULL
                                    )
);

