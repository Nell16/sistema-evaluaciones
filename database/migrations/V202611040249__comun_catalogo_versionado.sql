-- =====================================================
-- 8. VALIDACION DE VERSION EDITABLE
-- =====================================================

CREATE FUNCTION exigir_version_borrador(p_version_id BIGINT)
  RETURNS VOID
  LANGUAGE plpgsql
AS $$
DECLARE
v_estado VARCHAR(20);
BEGIN
SELECT estado
INTO v_estado
FROM version_formulario
WHERE id_version_formulario = p_version_id
  FOR UPDATE;

IF NOT FOUND THEN
        RAISE EXCEPTION
            'La version de formulario % no existe', p_version_id;
END IF;

    IF v_estado <> 'BORRADOR' THEN
        RAISE EXCEPTION
            'No se puede modificar una version publicada o retirada';
END IF;
END;
$$;

-- =====================================================
-- 9. CONTROL DEL CICLO DE VIDA DE LA VERSION
-- =====================================================

CREATE FUNCTION controlar_version_formulario()
  RETURNS TRIGGER
  LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.estado <> 'BORRADOR' THEN
            RAISE EXCEPTION
                'No se puede eliminar una version publicada o retirada';
END IF;

RETURN OLD;
END IF;

    IF NEW.id_version_formulario IS DISTINCT FROM OLD.id_version_formulario
       OR NEW.id_test IS DISTINCT FROM OLD.id_test THEN
        RAISE EXCEPTION
            'No se puede cambiar la identidad o el test de una version';
END IF;

    IF OLD.estado = 'BORRADOR' THEN

        IF NEW.estado NOT IN ('BORRADOR', 'PUBLICADA') THEN
            RAISE EXCEPTION
                'Una version en borrador solo puede publicarse';
END IF;

        IF NEW.estado = 'PUBLICADA'
           AND NOT EXISTS (
               SELECT 1
               FROM configuracion_subprueba
               WHERE id_version_formulario = OLD.id_version_formulario
           ) THEN
            RAISE EXCEPTION
                'Una version necesita configuraciones para publicarse';
END IF;

    ELSIF OLD.estado = 'PUBLICADA' THEN

        IF NEW.estado NOT IN ('PUBLICADA', 'RETIRADA') THEN
            RAISE EXCEPTION
                'Transicion de estado no permitida';
END IF;

        IF ROW(
            NEW.codigo_version,
            NEW.descripcion,
            NEW.fuente_ref,
            NEW.publicada_en,
            NEW.evidencia_validacion
        ) IS DISTINCT FROM ROW(
            OLD.codigo_version,
            OLD.descripcion,
            OLD.fuente_ref,
            OLD.publicada_en,
            OLD.evidencia_validacion
        ) THEN
            RAISE EXCEPTION
                'El contenido de una version publicada es inmutable';
END IF;

ELSE
        IF NEW IS DISTINCT FROM OLD THEN
            RAISE EXCEPTION
                'No se puede modificar una version retirada';
END IF;
END IF;

RETURN NEW;
END;
$$;

CREATE TRIGGER trg_control_version
  BEFORE UPDATE OR DELETE ON version_formulario
FOR EACH ROW
EXECUTE FUNCTION controlar_version_formulario();

-- =====================================================
-- 10. PROTEGER LA IDENTIDAD DE LAS SUBPRUEBAS
-- =====================================================

CREATE FUNCTION proteger_subprueba()
  RETURNS TRIGGER
  LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.id_subprueba IS DISTINCT FROM OLD.id_subprueba
       OR NEW.id_test IS DISTINCT FROM OLD.id_test THEN
        RAISE EXCEPTION
            'No se puede cambiar la identidad o el test de una subprueba';
END IF;

    IF ROW(NEW.codigo, NEW.nombre, NEW.descripcion)
       IS DISTINCT FROM
       ROW(OLD.codigo, OLD.nombre, OLD.descripcion)
       AND EXISTS (
           SELECT 1
           FROM configuracion_subprueba cs
           JOIN version_formulario vf
             ON vf.id_version_formulario = cs.id_version_formulario
           WHERE cs.id_subprueba = OLD.id_subprueba
             AND vf.estado IN ('PUBLICADA', 'RETIRADA')
       ) THEN
        RAISE EXCEPTION
            'No se puede redefinir una subprueba utilizada en versiones publicadas';
END IF;

RETURN NEW;
END;
$$;

CREATE TRIGGER trg_proteger_subprueba
  BEFORE UPDATE ON subprueba
  FOR EACH ROW
  EXECUTE FUNCTION proteger_subprueba();

-- =====================================================
-- 11. PROTEGER CONFIGURACIONES VERSIONADAS
-- =====================================================

CREATE FUNCTION controlar_configuracion()
  RETURNS TRIGGER
  LANGUAGE plpgsql
AS $$
DECLARE
v_test_version BIGINT;
    v_test_subprueba BIGINT;
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        PERFORM exigir_version_borrador(OLD.id_version_formulario);
END IF;

    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        PERFORM exigir_version_borrador(NEW.id_version_formulario);

SELECT id_test
INTO v_test_version
FROM version_formulario
WHERE id_version_formulario = NEW.id_version_formulario;

SELECT id_test
INTO v_test_subprueba
FROM subprueba
WHERE id_subprueba = NEW.id_subprueba;

IF v_test_subprueba IS DISTINCT FROM v_test_version THEN
            RAISE EXCEPTION
                'La subprueba no pertenece al mismo test que la version';
END IF;

        IF TG_OP = 'UPDATE' AND
           NEW.id_configuracion_subprueba IS DISTINCT FROM
           OLD.id_configuracion_subprueba THEN
            RAISE EXCEPTION
                'No se puede cambiar el ID de una configuracion';
END IF;

RETURN NEW;
END IF;

RETURN OLD;
END;
$$;

CREATE TRIGGER trg_control_configuracion
  BEFORE INSERT OR UPDATE OR DELETE ON configuracion_subprueba
  FOR EACH ROW
  EXECUTE FUNCTION controlar_configuracion();

-- =====================================================
-- 12. PROTEGER PREGUNTAS VERSIONADAS
-- =====================================================

CREATE FUNCTION controlar_pregunta()
  RETURNS TRIGGER
  LANGUAGE plpgsql
AS $$
DECLARE
v_version_id BIGINT;
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
SELECT id_version_formulario
INTO v_version_id
FROM configuracion_subprueba
WHERE id_configuracion_subprueba =
      OLD.id_configuracion_subprueba;

PERFORM exigir_version_borrador(v_version_id);
END IF;

    IF TG_OP IN ('INSERT', 'UPDATE') THEN
SELECT id_version_formulario
INTO v_version_id
FROM configuracion_subprueba
WHERE id_configuracion_subprueba =
      NEW.id_configuracion_subprueba;

PERFORM exigir_version_borrador(v_version_id);

        IF TG_OP = 'UPDATE'
           AND NEW.id_pregunta IS DISTINCT FROM OLD.id_pregunta THEN
            RAISE EXCEPTION
                'No se puede cambiar el ID de una pregunta';
END IF;

RETURN NEW;
END IF;

RETURN OLD;
END;
$$;

CREATE TRIGGER trg_control_pregunta
  BEFORE INSERT OR UPDATE OR DELETE ON pregunta
  FOR EACH ROW
  EXECUTE FUNCTION controlar_pregunta();

-- =====================================================
-- 13. PROTEGER OPCIONES VERSIONADAS
-- =====================================================

CREATE FUNCTION controlar_opcion()
  RETURNS TRIGGER
  LANGUAGE plpgsql
AS $$
DECLARE
v_version_id BIGINT;
    v_tipo_respuesta VARCHAR(20);
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
SELECT cs.id_version_formulario
INTO v_version_id
FROM pregunta p
       JOIN configuracion_subprueba cs
            ON cs.id_configuracion_subprueba =
               p.id_configuracion_subprueba
WHERE p.id_pregunta = OLD.id_pregunta;

PERFORM exigir_version_borrador(v_version_id);
END IF;

    IF TG_OP IN ('INSERT', 'UPDATE') THEN
SELECT cs.id_version_formulario, cs.tipo_respuesta
INTO v_version_id, v_tipo_respuesta
FROM pregunta p
       JOIN configuracion_subprueba cs
            ON cs.id_configuracion_subprueba =
               p.id_configuracion_subprueba
WHERE p.id_pregunta = NEW.id_pregunta;

PERFORM exigir_version_borrador(v_version_id);

        IF v_tipo_respuesta <> 'SELECCION' THEN
            RAISE EXCEPTION
                'Las opciones solo pertenecen a preguntas de seleccion';
END IF;

        IF TG_OP = 'UPDATE'
           AND NEW.id_opcion IS DISTINCT FROM OLD.id_opcion THEN
            RAISE EXCEPTION
                'No se puede cambiar el ID de una opcion';
END IF;

RETURN NEW;
END IF;

RETURN OLD;
END;
$$;

CREATE TRIGGER trg_control_opcion
  BEFORE INSERT OR UPDATE OR DELETE ON opcion_respuesta
  FOR EACH ROW
  EXECUTE FUNCTION controlar_opcion();
