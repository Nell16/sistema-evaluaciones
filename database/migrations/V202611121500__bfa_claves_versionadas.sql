
-- BFA-BE-09
-- Persistencia de claves de correccion versionadas.
-- No contiene respuestas oficiales ni datos psicometricos.

-- ============================================
-- 1. VERSIONES DE CLAVES BFA
-- ============================================

CREATE TABLE version_clave_bfa (
                                 id_clave BIGINT
                                   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                 id_version_formulario BIGINT NOT NULL,

                                 version VARCHAR(80) NOT NULL,

                                 estado VARCHAR(20) NOT NULL DEFAULT 'BORRADOR',

                                 referencia_fuente TEXT NOT NULL,

                                 evidencia_aprobacion TEXT,

                                 CONSTRAINT fk_clave_version_formulario
                                   FOREIGN KEY (id_version_formulario)
                                     REFERENCES version_formulario(id_version_formulario),

                                 CONSTRAINT uq_clave_formulario_version
                                   UNIQUE (id_version_formulario, version),

                                 CONSTRAINT chk_clave_version
                                   CHECK (BTRIM(version) <> ''),

                                 CONSTRAINT chk_clave_estado
                                   CHECK (estado IN (
                                                     'BORRADOR',
                                                     'APROBADA',
                                                     'RETIRADA'
                                     )),

                                 CONSTRAINT chk_clave_fuente
                                   CHECK (BTRIM(referencia_fuente) <> ''),

                                 CONSTRAINT chk_clave_evidencia
                                   CHECK (
                                     evidencia_aprobacion IS NULL
                                       OR BTRIM(evidencia_aprobacion) <> ''
                                     ),

                                 CONSTRAINT chk_clave_aprobacion
                                   CHECK (
                                     estado = 'BORRADOR'
                                       OR evidencia_aprobacion IS NOT NULL
                                     )
);

-- ============================================
-- 2. ENTRADAS DE CLAVES BFA
-- ============================================

CREATE TABLE entrada_clave_bfa (
                                 id_entrada_clave BIGINT
                                   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                 id_clave BIGINT NOT NULL,

                                 id_pregunta BIGINT NOT NULL,

                                 id_opcion_correcta BIGINT NOT NULL,

                                 CONSTRAINT fk_entrada_clave
                                   FOREIGN KEY (id_clave)
                                     REFERENCES version_clave_bfa(id_clave),

                                 CONSTRAINT fk_entrada_pregunta
                                   FOREIGN KEY (id_pregunta)
                                     REFERENCES pregunta(id_pregunta),

                                 CONSTRAINT fk_entrada_opcion
                                   FOREIGN KEY (id_opcion_correcta)
                                     REFERENCES opcion_respuesta(id_opcion),

                                 CONSTRAINT uq_entrada_clave_pregunta
                                   UNIQUE (id_clave, id_pregunta)
);

-- ============================================
-- 3. INDICES DE RELACIONES
-- ============================================

CREATE INDEX idx_clave_version_formulario
  ON version_clave_bfa(id_version_formulario);

CREATE INDEX idx_entrada_pregunta
  ON entrada_clave_bfa(id_pregunta);

CREATE INDEX idx_entrada_opcion
  ON entrada_clave_bfa(id_opcion_correcta);
