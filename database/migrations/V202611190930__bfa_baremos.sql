CREATE TABLE baremo_bfa (
    id_baremo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(200) NOT NULL,
    version VARCHAR(80) NOT NULL,
    anio_norma INTEGER NOT NULL,
    poblacion_referencia TEXT,
    referencia_fuente TEXT,
    CONSTRAINT uq_baremo_nombre_version UNIQUE (nombre, version),
    CONSTRAINT ck_baremo_anio CHECK (anio_norma > 0)
);

CREATE TABLE rango_baremo_bfa (
    id_rango BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_baremo BIGINT NOT NULL REFERENCES baremo_bfa(id_baremo),
    id_factor VARCHAR(80) NOT NULL,
    percentil INTEGER NOT NULL,
    limite_inferior INTEGER,
    limite_superior INTEGER,
    estado_celda VARCHAR(20) NOT NULL,
    valor_original TEXT,
    localizador_fuente TEXT,
    CONSTRAINT uq_rango_baremo_factor_percentil UNIQUE (id_baremo, id_factor, percentil),
    CONSTRAINT ck_rango_baremo_percentil CHECK (percentil BETWEEN 1 AND 99),
    CONSTRAINT ck_rango_baremo_estado CHECK (estado_celda IN ('RANGO', 'SIN_DATO')),
    CONSTRAINT ck_rango_baremo_limites CHECK (
        (estado_celda = 'RANGO' AND limite_inferior IS NOT NULL
            AND limite_superior IS NOT NULL AND limite_inferior <= limite_superior)
        OR (estado_celda = 'SIN_DATO' AND limite_inferior IS NULL AND limite_superior IS NULL)
    )
);
