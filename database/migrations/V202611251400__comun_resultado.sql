-- BFA-BE-38: Tablas para guardar el resultado de la evaluacion y sus factores calculados

CREATE TABLE IF NOT EXISTS resultado (
    id_resultado BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_evaluacion BIGINT NOT NULL UNIQUE,
    estado_resultado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE_VALIDACION',
    version_formulario_id BIGINT,
    fecha_calculo TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    referencia_revision_vigente VARCHAR(100),
    detalle TEXT,

    CONSTRAINT fk_resultado_evaluacion
        FOREIGN KEY (id_evaluacion) REFERENCES evaluacion(id_evaluacion) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS resultado_factor (
    id_resultado_factor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_resultado BIGINT NOT NULL,
    codigo VARCHAR(80) NOT NULL,
    puntuacion_directa INTEGER,
    estado_calculo VARCHAR(30) NOT NULL,
    percentil INTEGER,
    id_rango BIGINT,
    estado_normativo VARCHAR(30) NOT NULL,
    motivo VARCHAR(200),

    CONSTRAINT fk_resultado_factor_resultado
        FOREIGN KEY (id_resultado) REFERENCES resultado(id_resultado) ON DELETE CASCADE,
    CONSTRAINT uq_resultado_factor UNIQUE (id_resultado, codigo)
);

CREATE INDEX IF NOT EXISTS idx_resultado_evaluacion ON resultado(id_evaluacion);
