-- BFA-BE-38: Factores de resultado calculados y ampliacion compatible de resultado

ALTER TABLE resultado ADD COLUMN IF NOT EXISTS version_formulario_id BIGINT REFERENCES version_formulario(id_version_formulario);

-- Referencia privada usada por el calculo. FK coordinada con PR #95 antes de aceptar la migracion.
ALTER TABLE resultado ADD COLUMN IF NOT EXISTS id_clave_calculo BIGINT;

CREATE TABLE IF NOT EXISTS resultado_factor (
    id_resultado_factor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_resultado BIGINT NOT NULL REFERENCES resultado(id_resultado) ON DELETE CASCADE,
    codigo VARCHAR(80) NOT NULL,
    puntuacion_directa INTEGER,
    estado_calculo VARCHAR(30) NOT NULL,
    percentil INTEGER,
    id_rango BIGINT,
    estado_normativo VARCHAR(30) NOT NULL DEFAULT 'NO_APLICA',
    motivo VARCHAR(255),
    CONSTRAINT uq_resultado_factor UNIQUE (id_resultado, codigo)
);

CREATE INDEX IF NOT EXISTS idx_resultado_factor_resultado ON resultado_factor(id_resultado);
