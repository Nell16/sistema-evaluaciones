-- BFA-BE-31 (propuesta para el custodio de migraciones): revisiones de resultado BFA y
-- decisiones del psicólogo sobre las palabras de Fluidez Verbal (E10-E12).
-- Una revisión nueva no cambia la vigente; solo E12 cambia resultado.referencia_revision_vigente.

CREATE TABLE IF NOT EXISTS revision_resultado (
    id_revision_resultado BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_resultado BIGINT NOT NULL REFERENCES resultado(id_resultado),
    numero_revision INTEGER NOT NULL CHECK (numero_revision >= 1),
    motivo TEXT NOT NULL CHECK (BTRIM(motivo) <> ''),
    version_reglas VARCHAR(80),
    id_clave BIGINT, -- sin FK: version_clave_bfa aún no está en main
    id_baremo BIGINT, -- sin FK: baremo_bfa aún no está en main
    id_solicitud VARCHAR(80),
    id_cuenta_autor BIGINT NOT NULL REFERENCES cuenta(id_cuenta),
    creada_en TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp(),
    audiencia_publicacion TEXT,
    motivo_publicacion TEXT,
    publicada_en TIMESTAMPTZ,
    CONSTRAINT uq_revision_numero UNIQUE (id_resultado, numero_revision)
);

-- Reenviar la misma solicitud de recálculo devuelve la misma revisión.
CREATE UNIQUE INDEX IF NOT EXISTS uq_revision_solicitud
    ON revision_resultado(id_resultado, id_solicitud) WHERE id_solicitud IS NOT NULL;

CREATE TABLE IF NOT EXISTS revision_palabra (
    id_revision_palabra BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_revision_resultado BIGINT NOT NULL REFERENCES revision_resultado(id_revision_resultado),
    id_respuesta_evaluacion BIGINT NOT NULL REFERENCES respuesta_evaluacion(id_respuesta_evaluacion),
    decision VARCHAR(20) NOT NULL CHECK (decision IN ('VALIDA', 'INVALIDA', 'PENDIENTE')),
    motivo TEXT NOT NULL CHECK (BTRIM(motivo) <> ''),
    id_cuenta BIGINT NOT NULL REFERENCES cuenta(id_cuenta),
    fecha_decision TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp(),
    CONSTRAINT uq_revision_palabra UNIQUE (id_revision_resultado, id_respuesta_evaluacion)
);
