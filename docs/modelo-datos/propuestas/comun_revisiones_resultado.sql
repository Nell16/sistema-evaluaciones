-- FK de clave/baremo/rango corresponden a sus modulos aun no integrados.
-- DOC-34: reglas, revisiones, escalas y conversiones; pendiente de revision del custodio.
CREATE TABLE regla_calificacion (
 id_regla_calificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_version_formulario BIGINT NOT NULL REFERENCES version_formulario(id_version_formulario),
 version VARCHAR(80) NOT NULL,
 referencia_implementacion TEXT,
 estado TEXT NOT NULL CHECK(estado IN ('BORRADOR','APROBADA','RETIRADA')),
 referencia_especificacion TEXT NOT NULL CHECK(btrim(referencia_especificacion)<>''),
 evidencia_aprobacion TEXT,
 UNIQUE(id_version_formulario,version),
 CHECK(estado='BORRADOR' OR nullif(btrim(evidencia_aprobacion),'') IS NOT NULL)
);
CREATE TABLE revision_resultado (
 id_revision_resultado BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_resultado BIGINT NOT NULL REFERENCES resultado(id_resultado),
 id_regla_calificacion BIGINT REFERENCES regla_calificacion(id_regla_calificacion),
 id_clave BIGINT,
 id_baremo BIGINT,
 numero_revision INTEGER NOT NULL CHECK(numero_revision>0),
 fecha_calculo TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp(),
 estado_revision TEXT NOT NULL CHECK(estado_revision IN ('PENDIENTE','CALCULADA','VALIDADA')),
 id_cuenta BIGINT REFERENCES cuenta(id_cuenta),
 fecha_revision TIMESTAMPTZ,
 motivo TEXT,
 audiencia TEXT[] NOT NULL DEFAULT '{}',
 UNIQUE(id_resultado,numero_revision),
 UNIQUE(id_resultado,id_revision_resultado),
 CHECK(audiencia <@ ARRAY['SUJETO','ACADEMICO','COORDINADOR','PSICOLOGO','DECANO']::text[]),
 CHECK(estado_revision<>'VALIDADA' OR (id_cuenta IS NOT NULL AND fecha_revision IS NOT NULL AND nullif(btrim(motivo),'') IS NOT NULL))
);
ALTER TABLE resultado ADD CONSTRAINT fk_resultado_revision_vigente
 FOREIGN KEY(id_resultado,referencia_revision_vigente) REFERENCES revision_resultado(id_resultado,id_revision_resultado);
CREATE TABLE escala (
 id_escala BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_test BIGINT NOT NULL REFERENCES test(id_test),codigo VARCHAR(80) NOT NULL,nombre TEXT NOT NULL,
 UNIQUE(id_test,codigo)
);
CREATE TABLE puntaje_subprueba (
 id_puntaje_subprueba BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_revision_resultado BIGINT NOT NULL REFERENCES revision_resultado(id_revision_resultado),
 id_evaluacion_subprueba BIGINT NOT NULL REFERENCES evaluacion_subprueba(id_evaluacion_subprueba),
 puntaje_bruto INTEGER,estado_calculo TEXT NOT NULL,aciertos INTEGER,errores INTEGER,omisiones INTEGER,
 UNIQUE(id_revision_resultado,id_evaluacion_subprueba),
 CHECK(estado_calculo<>'CALCULADO' OR puntaje_bruto IS NOT NULL)
);
CREATE TABLE resultado_escala (
 id_resultado_escala BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_revision_resultado BIGINT NOT NULL REFERENCES revision_resultado(id_revision_resultado),
 id_escala BIGINT NOT NULL REFERENCES escala(id_escala),
 orden INTEGER NOT NULL CHECK(orden>0),puntaje_bruto INTEGER,
 estado_calculo TEXT NOT NULL,estado_normativo TEXT NOT NULL,motivo TEXT,
 UNIQUE(id_revision_resultado,id_escala),UNIQUE(id_revision_resultado,orden),
 CHECK(estado_calculo<>'CALCULADO' OR puntaje_bruto IS NOT NULL)
);
CREATE TABLE conversion_resultado_escala (
 id_conversion_resultado_escala BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_resultado_escala BIGINT NOT NULL REFERENCES resultado_escala(id_resultado_escala),
 tipo_salida TEXT NOT NULL,puntaje_convertido INTEGER,
 id_rango BIGINT,
 UNIQUE(id_resultado_escala,tipo_salida),
 CHECK(tipo_salida<>'PERCENTIL' OR (id_rango IS NOT NULL AND puntaje_convertido BETWEEN 1 AND 99))
);
